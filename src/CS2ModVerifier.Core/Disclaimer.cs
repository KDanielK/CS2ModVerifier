namespace CS2ModVerifier.Core;

/// <summary>
/// What the tool checks and its disclaimer, shown by every front end.
/// Keep in sync with the "What it checks" and "Disclaimer" sections of README.md.
/// </summary>
public static class Disclaimer
{
    public const string ChecksTitle = "What it checks";

    public const string Checks =
        """
        CS2 Mod Verifier compares mod DLLs with their published source and checks each installed Cities: Skylines II mod:

        1. Source comparison. Takes the GitHub link from the mod's Paradox Mods page, finds the commit the mod was built from, and compares the types and method signatures in the mod's DLL with that source. Reports every type or method in the DLL that is not in the source. It also traces each risky call (starting programs, internet access, loading code at runtime, native Windows functions, the registry) to the method that makes it, and shows the file and line in the source where that call appears, or reports it when the source does not contain it. Code generated by the C# compiler and the game's build tools is listed separately rather than hidden. A mod without a GitHub link is reported as having no source to compare.
        2. File integrity. Compares the SHA-256 hash of every file with the file list Paradox Mods delivered with the mod. Reports files that were changed, removed or added after download.
        3. Unexpected files. Identifies each file by its content, not its name. Reports programs, scripts, native libraries other than the standard ones that every code mod ships, and files disguised with a different extension. Also lists extra .NET libraries bundled with a mod, and recognises official builds of Harmony by comparing their SHA-256 hash with Harmony's GitHub releases. The tool ships with a list of known builds and looks up newer versions in Harmony's releases when a mod uses one. A file named like Harmony that matches no official build is reported.
        4. Code references. Reads each mod DLL as data, without loading or running it, and lists the system features its code refers to: internet access, starting programs, loading other code at runtime, native Windows functions, the Windows registry, files and folders, user folders such as AppData, and suspicious text such as web addresses.
        """;

    public const string Title = "Disclaimer";

    public const string Text =
        """
        CS2 Mod Verifier is an aid, not a guarantee of safety.

        - No findings does not mean a mod is safe. The tool only finds what the checks above look for. Code can be written to avoid them.
        - A finding does not mean a mod is harmful. It is a reason to take a closer look. Many legitimate mods use these features, for example file access to save their settings.
        - Matching the source does not prove the source is harmless. The source comparison checks that the DLL's types, method signatures and risky calls appear in the source. A call found in the source can be read there, but that does not mean anyone has reviewed it. The rest of the code inside each method is not compared.
        - Matching the Paradox file list does not prove the upload is genuine. It shows the files are the ones Paradox delivered. If an author's account is compromised, Paradox delivers the attacker's files.
        - Native code is not inspected. Native libraries are only identified by name and hash.
        - Asset mods are not checked. Only mods tagged "Code Mod" on Paradox Mods, or with a .dll in their main folder, are checked; code hidden in other mods is not found.
        - Only install mods from sources you trust. You are responsible for what you install.

