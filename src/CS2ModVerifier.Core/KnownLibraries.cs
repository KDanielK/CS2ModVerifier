using System.Text.Json;

namespace CS2ModVerifier.Core;

/// <summary>An official build of a common library, identified by its SHA-256 hash.</summary>
public sealed record KnownLibrary(string Name, string FileName, string Version, string Build, string Sha256, string Source);

/// <summary>Where a library's official builds are published: its GitHub repository, fixed in the tool's data.</summary>
public sealed record LibrarySource(string Name, string FileName, string Repository);

/// <summary>
/// Official builds of libraries that mods commonly bundle, such as Harmony. A starting list ships inside this DLL
/// (known-libraries.json, generated by tools/Update-KnownLibraries.ps1). Versions found later are added from the
/// library's GitHub releases by the source-comparison layer and remembered in a local file; this class itself
/// never uses the network.
/// </summary>
public static class KnownLibraries
{
    private static readonly JsonSerializerOptions Options = new() { WriteIndented = true, PropertyNamingPolicy = JsonNamingPolicy.CamelCase };
    private static readonly Lock Gate = new();
    private static readonly List<KnownLibrary> Libraries = [];
    private static readonly HashSet<string> MissingVersions = new(StringComparer.OrdinalIgnoreCase);
    private static readonly List<LibrarySource> SourceList = [];
    private static string? localPath;

    static KnownLibraries()
    {
        using var stream = typeof(KnownLibraries).Assembly.GetManifestResourceStream("CS2ModVerifier.Core.known-libraries.json")
            ?? throw new InvalidOperationException("The known-libraries list is missing from the build.");
        var data = JsonSerializer.Deserialize<ListFile>(stream, Options) ?? new ListFile();
        Libraries.AddRange(data.Libraries);
        SourceList.AddRange(data.Sources);
    }

    public static IReadOnlyList<KnownLibrary> All
    {
        get
        {
            lock (Gate)
            {
                return [.. Libraries];
            }
        }
    }

    public static IReadOnlyList<LibrarySource> Sources => SourceList;

    /// <summary>The per-user file with versions learned since the release: %LOCALAPPDATA%\CS2ModVerifier\known-libraries.json.</summary>
    public static string DefaultLocalPath() =>
        Path.Combine(Environment.GetFolderPath(Environment.SpecialFolder.LocalApplicationData), "CS2ModVerifier", "known-libraries.json");

    /// <summary>Loads versions learned earlier, and remembers where to save new ones. Call once at startup.</summary>
    public static void UseLocalFile(string path)
    {
        lock (Gate)
        {
            localPath = path;
            try
            {
                using var stream = File.OpenRead(path);
                var data = JsonSerializer.Deserialize<ListFile>(stream, Options) ?? new ListFile();
                var known = Libraries.Select(l => l.Sha256).ToHashSet(StringComparer.OrdinalIgnoreCase);
                Libraries.AddRange(data.Libraries.Where(l => known.Add(l.Sha256)));
                MissingVersions.UnionWith(data.MissingVersions);
            }
            catch (Exception e) when (e is IOException or UnauthorizedAccessException or JsonException)
            {
                // Nothing learned yet.
            }
        }
    }

    /// <summary>Adds builds found in a library's official releases, and saves them to the local file.</summary>
    public static void Learn(IEnumerable<KnownLibrary> builds)
    {
        lock (Gate)
        {
            var known = Libraries.Select(l => l.Sha256).ToHashSet(StringComparer.OrdinalIgnoreCase);
            Libraries.AddRange(builds.Where(b => known.Add(b.Sha256)));
            SaveLearned();
        }
    }

    /// <summary>Remembers that the library's releases contain no such version, so it is not looked up again.</summary>
    public static void LearnMissing(string name, string version)
    {
        lock (Gate)
        {
            MissingVersions.Add(name + "|" + Normalize(version));
            SaveLearned();
        }
    }

    public static KnownLibrary? FindByHash(string sha256Hex) =>
        All.FirstOrDefault(l => string.Equals(l.Sha256, sha256Hex, StringComparison.OrdinalIgnoreCase));

    /// <summary>The library a file is named after, by file name or assembly name ("0Harmony"), or null.</summary>
    public static string? NameFor(string fileName, string? assemblyName) =>
        Sources.FirstOrDefault(s => string.Equals(s.FileName, Path.GetFileName(fileName), StringComparison.OrdinalIgnoreCase)
            || string.Equals(Path.GetFileNameWithoutExtension(s.FileName), assemblyName, StringComparison.OrdinalIgnoreCase))?.Name;

    /// <summary>Whether this version of the library is in the list ("2.4.3" equals "2.4.3.0").</summary>
    public static bool IsKnownVersion(string name, string? version) =>
        version is not null && All.Any(l => l.Name == name && Normalize(l.Version) == Normalize(version));

    /// <summary>Whether the library's releases were checked and contain no such version.</summary>
    public static bool IsMissingVersion(string name, string? version)
    {
        lock (Gate)
        {
            return version is not null && MissingVersions.Contains(name + "|" + Normalize(version));
        }
    }

    /// <summary>"2.4.3" and "2.4.3.0" both become "2.4.3.0"; text that is not a version stays as it is.</summary>
    public static string Normalize(string version) =>
        System.Version.TryParse(version, out var v)
            ? new System.Version(v.Major, v.Minor, Math.Max(v.Build, 0), Math.Max(v.Revision, 0)).ToString()
            : version;

    private static void SaveLearned()
    {
        if (localPath is null)
        {
            return;
        }

        // Only what is not in the built-in list goes to the local file.
        var builtIn = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        using (var stream = typeof(KnownLibraries).Assembly.GetManifestResourceStream("CS2ModVerifier.Core.known-libraries.json"))
        {
            var data = JsonSerializer.Deserialize<ListFile>(stream!, Options) ?? new ListFile();
            builtIn.UnionWith(data.Libraries.Select(l => l.Sha256));
        }

        var learned = new ListFile
        {
            GeneratedBy = "CS2 Mod Verifier, from the libraries' GitHub releases",
            Libraries = [.. Libraries.Where(l => !builtIn.Contains(l.Sha256))],
            MissingVersions = [.. MissingVersions.Order(StringComparer.Ordinal)],
        };
        Directory.CreateDirectory(Path.GetDirectoryName(localPath)!);
        var temp = localPath + ".tmp";
        File.WriteAllText(temp, JsonSerializer.Serialize(learned, Options));
        File.Move(temp, localPath, overwrite: true);
    }

    private sealed class ListFile
    {
        public string? GeneratedBy { get; set; }

        public List<LibrarySource> Sources { get; set; } = [];

        public List<KnownLibrary> Libraries { get; set; } = [];

        public List<string> MissingVersions { get; set; } = [];
    }
}

/// <summary>
/// Groups the findings of a recognised official library under one finding, and flags files that are
/// named like a known library but match none of its official builds.
/// </summary>
public static class LibraryRules
{
    public static List<Finding> Apply(IReadOnlyList<ModFile> inventory, IReadOnlyList<AssemblyReport> assemblies, List<Finding> findings)
    {
        foreach (var file in inventory.Where(f => f.Kind == FileKind.ManagedAssembly))
        {
            var assembly = assemblies.FirstOrDefault(a => a.RelativePath == file.RelativePath);
            var name = KnownLibraries.NameFor(file.RelativePath, assembly?.Name);
            if (name is null)
            {
                continue;
            }

            if (KnownLibraries.FindByHash(file.Sha256Hex) is { } known)
            {
                // The capabilities are the library's, and identical in every mod that bundles this build:
                // one finding to review and accept, the details kept as Info.
                var capabilities = findings
                    .Where(f => f.File == file.RelativePath && f.Severity >= Severity.Medium && f.Category != "SuspiciousStrings")
                    .OrderByDescending(f => f.Severity)
                    .Select(f => f.Category)
                    .Distinct()
                    .ToList();
                findings = [.. findings
                    .Where(f => !(f.File == file.RelativePath && f.Category == "ExtraAssembly"))
                    .Select(f => f.File == file.RelativePath && f.Severity > Severity.Info
                        ? f with { Severity = Severity.Info, Message = $"Part of official {known.Name}: {f.Message}" }
                        : f)];
                var summary = capabilities.Count == 0 ? string.Empty : $"; it can {Describe(capabilities)}";
                findings.Add(new Finding(Severity.Medium, "KnownLibrary",
                    $"Official {known.Name} {known.Version}, build {known.Build.Replace(" (", ", ").TrimEnd(')')}, identical to its GitHub release{summary}", file.RelativePath));
                continue;
            }

            var version = assembly?.Version;
            if (KnownLibraries.IsKnownVersion(name, version))
            {
                findings.Add(new Finding(Severity.High, "UnofficialLibrary",
                    $"Named like {name} {version}, but matches none of the official {name} {version} builds", file.RelativePath));
            }
            else if (KnownLibraries.IsMissingVersion(name, version))
            {
                findings.Add(new Finding(Severity.High, "UnofficialLibrary",
                    $"Named like {name} {version}, but {name} has no official release of that version", file.RelativePath));
            }
            else
            {
                findings.Add(new Finding(Severity.Medium, "UnlistedLibrary",
                    $"Named like {name}, version {version ?? "unknown"}, which could not be checked against {name}'s official releases yet", file.RelativePath));
            }
        }

        return findings;
    }

    private static string Describe(IReadOnlyList<string> categories)
    {
        var phrases = categories.Select(c => c switch
        {
            "DynamicCode" => "generate code while the game runs",
            "NativeInterop" => "call Windows functions directly",
            "Process" => "start programs",
            "Network" => "connect to the internet",
            "NetworkWithFileAccess" => "read files and send them over the internet",
            "Registry" => "use the Windows registry",
            _ => c,
        }).ToList();
        return phrases.Count == 1 ? phrases[0] : string.Join(", ", phrases[..^1]) + " and " + phrases[^1];
    }
}
