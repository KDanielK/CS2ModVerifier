using CS2ModVerifier.Core;

namespace CS2ModVerifier.SourceCompare;

/// <summary>
/// One risky call in the DLL, and whether the same method in the published source contains it.
/// </summary>
/// <param name="Api">Readable name, e.g. "Process.Start" or "native call kernel32!GetCurrentProcess".</param>
/// <param name="Method">The hand-written method making the call, e.g. "ParkingControl.ShellOpen::TryOpenWithOsShell".</param>
/// <param name="File">Source file (relative to the repository) and line where the call appears, or where the method starts.</param>
public sealed record CallTrace(string Category, Severity Severity, string Api, string Method, bool InSource, string? File, int? Line, string? Reason);

/// <summary>
/// Traces every risky call in a DLL to the method that makes it, and checks that this method's published source
/// mentions the same API. Syntax only: it shows the call is in the readable source, not what the call does.
/// </summary>
public static class CallTracer
{
    public static IReadOnlyList<CallTrace> Trace(DllModel dll, SourceModel source)
    {
        var traces = new Dictionary<string, CallTrace>(StringComparer.Ordinal);
        foreach (var method in dll.Types.SelectMany(t => t.Methods))
        {
            foreach (var call in method.Calls)
            {
                if (RiskRules.ClassifyCall(call) is not { } risk)
                {
                    continue;
                }

                var api = Display(call);
                var owner = $"{method.OwnerTypeKey}::{method.OwnerName}";
                var key = $"{risk.Category}|{api}|{owner}";
                if (!traces.ContainsKey(key))
                {
                    traces[key] = Locate(source, method, call, risk.Category, risk.Severity, api, owner);
                }
            }
        }

        // One line per method and kind of risk: setting ProcessStartInfo properties next to Process.Start adds nothing.
        // A call that is not in the source always stays, so nothing missing is hidden by the grouping.
        var grouped = traces.Values
            .GroupBy(t => (t.Category, t.Method))
            .SelectMany(g => g.Any(t => !t.InSource)
                ? g.Where(t => !t.InSource)
                : [g.OrderBy(t => IsAccessor(t.Api)).ThenBy(t => t.Api.StartsWith("new ", StringComparison.Ordinal)).First()]);
        return [.. grouped.OrderBy(t => t.InSource).ThenByDescending(t => t.Severity).ThenBy(t => t.Method, StringComparer.Ordinal)];
    }

    private static bool IsAccessor(string api) =>
        api.Contains(".get_", StringComparison.Ordinal) || api.Contains(".set_", StringComparison.Ordinal);

    private static CallTrace Locate(SourceModel source, DllMethod method, string call, string category, Severity severity, string api, string owner)
    {
        // Code the build tools generate has no source, and has no reason to make risky calls.
        if (GeneratedCodeRules.Match(method.OwnerName) is not null || GeneratedCodeRules.KnownToolchainTypes.Any(t => t.MatchesKey(method.OwnerTypeKey)))
        {
            return new(category, severity, api, owner, false, null, null, "it is in code generated by the build tools, which has no source");
        }

        if (!source.Types.TryGetValue(method.OwnerTypeKey, out var type))
        {
            return new(category, severity, api, owner, false, null, null, "its type is not in the source");
        }

        if (!type.Bodies.TryGetValue(method.OwnerName, out var bodies) || bodies.Count == 0)
        {
            return new(category, severity, api, owner, false, null, null, "the method is not in the source");
        }

        var identifier = Identifier(call);
        foreach (var body in bodies)
        {
            if (body.Identifiers.TryGetValue(identifier, out var line))
            {
                return new(category, severity, api, owner, true, body.File, line, null);
            }
        }

        return new(category, severity, api, owner, false, bodies[0].File, bodies[0].Line, $"the method's source does not mention {identifier}");
    }

    /// <summary>The name that must appear in the source: the member ("Start"), the type for constructors, the property for accessors.</summary>
    public static string Identifier(string call)
    {
        if (call.StartsWith("native:", StringComparison.Ordinal))
        {
            return call[(call.IndexOf('!') + 1)..];
        }

        var separator = call.IndexOf("::", StringComparison.Ordinal);
        var member = call[(separator + 2)..];
        if (member == ".ctor")
        {
            return TypeNames.StripArity(SimpleName(call[..separator]));
        }

        foreach (var prefix in (string[])["get_", "set_", "add_", "remove_"])
        {
            if (member.StartsWith(prefix, StringComparison.Ordinal))
            {
                return member[prefix.Length..];
            }
        }

        return member;
    }

    private static string Display(string call)
    {
        if (call.StartsWith("native:", StringComparison.Ordinal))
        {
            return "native call " + call["native:".Length..];
        }

        var separator = call.IndexOf("::", StringComparison.Ordinal);
        var type = TypeNames.StripArity(SimpleName(call[..separator]));
        var member = call[(separator + 2)..];
        return member == ".ctor" ? $"new {type}" : $"{type}.{member}";
    }

    private static string SimpleName(string typeName) => typeName[(typeName.LastIndexOf('.') + 1)..];
}
